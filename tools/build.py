"""Build both student pages from the single master library.

  python3 tools/build.py

Sources
  library/geoXL.txt                 master library: every function, written once
  library/geolab.txt                the laboratory list (names); functions they call are added automatically
  documentation/function-help.txt   argument help, returns and method notes (both pages)
  documentation/geoxl-guide.html, geoxl-install-notes.html, geoxl-groups.json   geoXL page text
  documentation/geolab-guide.html   geolabXL page text
  tools/page.css, tools/page.js, tools/updater-core.js, tools/vendor/jszip.min.js

Outputs (GitHub Pages serves docs/)
  docs/index.html, docs/update.html, docs/library/...           geoXL (all functions)
  docs/lab/index.html, docs/lab/update.html, docs/lab/library/  geolabXL (laboratory subset)
  docs/releases/<v>/ and docs/lab/releases/<v>/                 frozen copy of each release page

A published library snapshot is never overwritten: change the version first.
"""
import hashlib, html, json, re, shutil, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
DOC = ROOT / "documentation"
E = lambda t: html.escape(str(t), quote=False)
read = lambda p: Path(p).read_text(encoding="utf-8")

# ---------------------------------------------------------------- master library
master = read(ROOT / "library/geoXL.txt")

def definitions(lib):
    """Ordered list of (name, segment text including its /** */ comment, body)."""
    out = []
    for m in re.finditer(r"(/\*\*(?:(?!\*/)[\s\S])*?\*/\s*\n)?^([A-Za-z_]\w*)\s*=\s*", lib, re.M):
        i, depth, quoted = m.end(), 0, False
        while i < len(lib):
            c = lib[i]
            if c == '"': quoted = not quoted
            elif not quoted:
                if c in "({": depth += 1
                elif c in ")}": depth -= 1
                elif c == ";" and depth == 0: break
            i += 1
        out.append((m.group(2), lib[m.start():i + 1].strip(), lib[m.end():i]))
    return out

DEFS = definitions(master)
BYNAME = {n.lower(): (n, seg, body) for n, seg, body in DEFS}
gx_version = re.search(r"GeoEXCEL\s+version\s+([\w.\-]+)", master).group(1)
stamp = re.search(r'^version\s*=\s*LAMBDA\("GeoEXCEL\s+([\w.\-]+)\s+\((\d{4}-\d{2}-\d{2})\)"\)', master, re.M)
if not stamp or stamp.group(1) != gx_version: sys.exit(f"version() must return 'GeoEXCEL {gx_version} (YYYY-MM-DD)'")
gx_date = stamp.group(2)

# ---------------------------------------------------------------- laboratory subset
spec = read(ROOT / "library/geolab.txt")
lab_version = re.search(r"^version:\s*(\S+)", spec, re.M).group(1)
lab_date = re.search(r"^date:\s*(\S+)", spec, re.M).group(1)
wanted = [l.strip() for l in spec.splitlines() if l.strip() and not l.lstrip().startswith("#") and ":" not in l]
unknown = [w for w in wanted if w.lower() not in BYNAME]
if unknown: sys.exit("library/geolab.txt names functions not in library/geoXL.txt: " + ", ".join(unknown))

def references(body):
    body = re.sub(r'"[^"]*"', '""', body)
    return {t.lower() for t in re.findall(r"(?<![\w.])([A-Za-z_]\w*)", body)} & set(BYNAME)

lab_set, todo, added = set(), [w.lower() for w in wanted], []
while todo:
    k = todo.pop()
    if k in lab_set: continue
    lab_set.add(k)
    for r in references(BYNAME[k][2]):
        if r not in lab_set:
            todo.append(r)
            if r not in {w.lower() for w in wanted}: added.append(BYNAME[r][0])
lab_set.discard("version")
lab_defs = [d for d in DEFS if d[0].lower() in lab_set]
lab_text = (f"// geolabXL version {lab_version} — laboratory subset of geoXL {gx_version} (documented)\n"
            f"// Module name: geolabXL\n"
            f"// Generated by tools/build.py from library/geoXL.txt and library/geolab.txt. Do not edit; edit the master.\n"
            f"// Check the installed version with =geolab_version()\n\n"
            f"/** geolabXL library version and date. */\n"
            f'geolab_version = LAMBDA("geolabXL {lab_version} ({lab_date})");\n\n'
            + "\n\n".join(seg for _, seg, _ in lab_defs) + "\n")

# ---------------------------------------------------------------- snapshots
def snapshot(base, version, text, date):
    snap = base / "library/releases" / version / "library.txt"
    if snap.exists() and read(snap) != text:
        sys.exit(f"{snap.relative_to(ROOT)} is published with different content: raise the version")
    snap.parent.mkdir(parents=True, exist_ok=True); snap.write_text(text, encoding="utf-8")
    record = {"version": version, "library": f"releases/{version}/library.txt",
              "sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(), "published": date,
              "status": "published on the owner's authorization; native Excel release validation pending"}
    (base / "library/current.json").write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8")
    return record

gx_record = snapshot(DOCS, gx_version, master, gx_date)
lab_record = snapshot(DOCS / "lab", lab_version, lab_text, lab_date)

# ---------------------------------------------------------------- help text
helpdb, cur = {}, None
for ln in read(DOC / "function-help.txt").splitlines():
    if not ln.strip() or ln.lstrip().startswith("#"): continue
    m = re.match(r"\s*\[(\w+)\]\s*$", ln)
    if m: cur = helpdb.setdefault(m.group(1).lower(), {"params": {}, "returns": "", "notes": []}); continue
    if cur is None or ":" not in ln: sys.exit("function-help.txt: cannot read line: " + ln)
    k, v = (t.strip() for t in ln.split(":", 1))
    if k == "returns": cur["returns"] = v
    elif k == "notes": cur["notes"].append(v)
    else: cur["params"][k] = v

def signature(text):
    """Parameter list of each documented definition in a library text."""
    out = []
    for m in re.finditer(r"/\*\*((?:(?!\*/)[\s\S])*?)\*/\s*\n\s*([A-Za-z_]\w*)\s*=\s*", text):
        name, desc, rest = m.group(2), " ".join(m.group(1).split()), text[m.end():]
        params = None
        if rest.startswith("LAMBDA("):
            depth, cur, args, i = 0, "", [], len("LAMBDA(")
            while i < len(rest):
                c = rest[i]
                if c == '"':
                    j = rest.index('"', i + 1); cur += rest[i:j + 1]; i = j + 1; continue
                if c in "({": depth += 1
                if c in ")}":
                    if depth == 0: args.append(cur); break
                    depth -= 1
                if c == "," and depth == 0: args.append(cur); cur = ""
                else: cur += c
                i += 1
            params = [a.strip() for a in args[:-1]]
        out.append((name, desc, params))
    return out

HIDE_NOTE = re.compile(r"(Updated in geoXL|Corrected in geoXL|Uses the corrected geoXL|From 0\.14|The former |Stored in the library like)")
def card(name, desc, params, helpers):
    h = helpdb.get(name.lower(), {"params": {}, "returns": "", "notes": []})
    anchor, rows = name.upper(), ""
    call = "=" + name if params is None else "=" + name + "(" + ", ".join(params) + ")"
    for p in params or []:
        pn = p.strip("[]")
        rows += f"<tr><td><code>{E(pn)}</code>{' (optional)' if p.startswith('[') else ''}</td><td>{E(h['params'].get(pn, ''))}</td></tr>"
    kind = "Helper function" if name.lower() in helpers else "Worksheet function"
    body = f"<p class=function-kind>{kind}</p><p class=desc>{E(desc)}</p>"
    if rows: body += f"<table class=args><thead><tr><th>Argument</th><th>Meaning</th></tr></thead><tbody>{rows}</tbody></table>"
    if h["returns"]: body += f"<p><b>Returns:</b> {E(h['returns'])}</p>"
    notes = [re.sub(r" Added in geoXL [0-9.]+\.?", "", n) for n in h["notes"] if not HIDE_NOTE.match(n)]
    if notes: body += "<details class=method><summary>Method and assumptions</summary>" + "".join(f"<p>{E(n)}</p>" for n in notes) + "</details>"
    return f'<section class=fn id="{anchor}"><h3><a href="#{anchor}">{E(call)}</a></h3>{body}</section>'

